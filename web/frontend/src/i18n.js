export function useLanguage(){
  const [language,setLanguage]=useState(()=>localStorage.getItem('music-language')||'en');
  useEffect(()=>localStorage.setItem('music-language',language),[language]);
  const t=useCallback((value)=>{
    if(language==='vi') return translations.vi[value]||value;
    return value;
  },[language]);
  return {language,setLanguage,t};
}
